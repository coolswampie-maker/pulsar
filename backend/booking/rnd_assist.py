"""
Подбор исследований и испытаний по задаче, описанной своими словами.

Отличие от `assist.py`: там подбираются позиции для брони — прибор, комната,
специалист, и у каждой есть цена. Здесь подбирается работа: готовая методика
или испытание, которое выполнят под ключ. Цены у них нет ни у одной, срок
называет исполнитель после разбора задачи.

Правило то же, что и везде: что бы ни вернула модель, наружу уходят только
работы, которые действительно есть в каталоге. Модель выбирает из списка
пронумерованных строк, ответ сверяется с каталогом, всё лишнее выбрасывается.

Приборы в подбор тоже попадают: запрос «нужен растровый электронный микроскоп»
надо на что-то отвечать, даже если готовой работы под него нет. Но заказывают
их по-разному — работу заявкой, прибор бронью, — поэтому они возвращаются
отдельными списками, а не в одной куче.
"""
import logging
import re

from django.conf import settings

from .assist import (LICENSED_REPLY, MAX_QUERY_LEN, MAX_REPLY_LEN,
                     RELEVANCE_FLOOR, STOPWORDS, _match, ask_model,
                     json_from_text, needs_license, rank_local)
from .rnd_catalog import works as rnd_works

log = logging.getLogger(__name__)

MAX_WORKS = 6        # больше шести строк подряд человек уже не читает
MAX_ITEMS = 3        # приборы — дополнение к работам, а не вторая выдача


def _line(w):
    """Одна строка каталога для модели. Коротко: смысл выбора несут название,
    вид, отрасль, объект и номера стандартов, всё остальное — вода."""
    std = (w.get('std') or '')[:90]
    kw = (w.get('kw') or '')[:80]
    return ' | '.join([
        w.get('c') or '',
        w.get('n') or '',
        w.get('g') or '',
        ' / '.join(w.get('o') or []) or '—',
        w.get('obj') or '—',
        std or '—',
        kw or '—',
    ])


def _catalog_for_prompt(items):
    return '\n'.join(_line(w) for w in items)


def _resources_for_prompt(resources):
    lines = []
    for r in resources:
        specs = '; '.join((r.specs or [])[:3]) if isinstance(r.specs, list) else ''
        lines.append(f'{r.slug} | {r.get_type_display()} | {r.title} | {r.lab} | {specs}')
    return '\n'.join(lines)



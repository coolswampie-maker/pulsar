REPLY_EMPTY = ('Готовой методики под такое описание в каталоге нет. Задачу можно '
               'поставить как НИОКР — опишите её в заявке, оператор разберёт.')
REPLY_LOCAL = 'Вот что нашлось по словам из вашего описания:'


def _ask(query, items, resources):
    text = ask_model(
        SYSTEM_PROMPT,
        'КАТАЛОГ РАБОТ (код | название | вид исследования | отрасль | '
        'объект | стандарты | ключевые слова):\n'
        + _catalog_for_prompt(items)
        + '\n\nПРИБОРЫ И ПЛОЩАДКИ (слаг | тип | название | подразделение | '
          'характеристики):\n'
        + _resources_for_prompt(resources)
        + f'\n\nЗАДАЧА КЛИЕНТА: {query}',
        temperature=0.1,             # подбор, а не сочинение: нужна стабильность
        max_tokens=900,
        timeout=settings.ASSIST_TIMEOUT)
    return None if text is None else json_from_text(text)


def _pick(raw, valid, limit):
    """Сверка ответа модели с каталогом. Возвращает пары (ключ, обоснование)."""
    out, seen = [], set()
    if not isinstance(raw, list):
        return out
    for item in raw:
        if not isinstance(item, dict):
            continue
        key = str(item.get('id') or '').strip()
        if key not in valid or key in seen:
            continue
        seen.add(key)
        out.append((key, str(item.get('why') or '').strip()[:300]))
        if len(out) >= limit:
            break
    return out


def _local(query, items):
    """Запасной подбор без модели: совпадение слов по названию, объекту,
    ключевым словам и номерам стандартов. Хуже модели, но лучше пустого
    экрана — и подписывается как поиск, а не как работа ИИ.

    Сравнение берём из подбора оборудования (`assist._match`): там уже
    учтены окончания и словарь синонимов, и второй такой же алгоритм
    рядом означал бы, что правку одного забудут внести в другой.
    """
    words = [w for w in re.split(r'[\s,;.]+', query.lower())
             if len(w) > 2 and w not in STOPWORDS]
    if not words:
        return []
    scored = []
    for i, w in enumerate(items):
        strong = ' '.join([w.get('n') or '', w.get('kw') or '',
                           w.get('obj') or '']).lower()
        whole = ' '.join([strong, w.get('g') or '', ' '.join(w.get('o') or []),
                          w.get('std') or '', w.get('cond') or '']).lower()
        sc = 0
        for q in words:
            if _match(strong, q):
                sc += 3
            elif _match(whole, q):
                sc += 1
        if sc:
            scored.append((sc, i))
    if not scored:
        return []
    scored.sort(key=lambda x: -x[0])
    # отсекаем всё, что заметно слабее лучшего: одно случайное совпадение
    # из шести слов — это не «подходит», это шум
    best = scored[0][0]
    return [(items[i].get('c'), '') for sc, i in scored[:MAX_WORKS]
            if sc >= best * RELEVANCE_FLOOR and items[i].get('c')]


def rnd_assist(query, resources):
    """Точка входа.

    Возвращает (работы, приборы, режим, реплика). Работы и приборы — списки
    пар (объект, обоснование). Режимы те же, что у подбора оборудования:
    licensed / ai / local / empty — чтобы интерфейс подписывал выдачу честно
    и не выдавал поиск по словам за ответ модели.
    """
    query = (query or '').strip()[:MAX_QUERY_LEN]
    if not query:
        return [], [], 'empty', ''

    # Проверка до обращения к модели: не зависит от промпта, работает и при
    # отключённой модели, и её нельзя обойти уговорами в тексте запроса.
    if needs_license(query):
        log.info('Запрос отнесён к требующим разрешений, к модели не обращаемся')
        return [], [], 'licensed', LICENSED_REPLY

    items = rnd_works()
    if not items:
        log.warning('Каталог работ пуст — подбор по работам невозможен')
        return [], [], 'local', REPLY_EMPTY

    # Ключ — код работы. Названия не уникальны: «Определение рН» есть в
    # каталоге пять раз для разной продукции, и по названию подбор поднимал
    # бы не ту строку. Работы без кода в подбор не отдаём вовсе.
    by_work = {w['c']: w for w in items if w.get('c')}
    by_res = {r.slug: r for r in resources}

    data = _ask(query, items, resources)
    if data is not None:
        reply = str(data.get('reply') or '').strip()[:MAX_REPLY_LEN]
        picked = _pick(data.get('works'), by_work, MAX_WORKS)
        extra = _pick(data.get('items'), by_res, MAX_ITEMS)
        # Реплика без позиций — нормальный ответ: так модель отвечает на «кто ты»
        # и когда в каталоге действительно ничего нет. Но если модель что-то
        # предлагала и всё оказалось выдумкой, её реплику («вот три подходящих
        # испытания») показывать нельзя — она описывает то, что мы выбросили.
        if picked or extra:
            return ([(by_work[k], why) for k, why in picked],
                    [(by_res[k], why) for k, why in extra], 'ai', reply)
        if reply and not data.get('works') and not data.get('items'):
            return [], [], 'ai', reply
        log.info('Модель не дала ни реплики, ни существующих работ — локальный подбор')

    found = _local(query, items)
    res_found, _ = rank_local(query, resources)
    if not found and not res_found:
        return [], [], 'local', REPLY_EMPTY
    return ([(by_work[k], '') for k, _ in found],
            [(r, '') for r in res_found[:MAX_ITEMS]], 'local', REPLY_LOCAL)

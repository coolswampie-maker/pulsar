def _sections_task(key):
    """Задание по разделам — списком, а не одной слипшейся фразой."""
    rows = []
    for i, (name, what, size) in enumerate(SECTIONS[key], 1):
        rows.append(f'{i}. {name}\n   Что в разделе: {what}\n   Объём: {size}')
    return '\n'.join(rows)



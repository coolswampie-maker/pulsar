def missing_for(profile, fmt):
    """Каких обязательных полей не хватает для формата."""
    spec = FORMATS[fmt]
    return profile.missing(spec['needs'])


def _ask_model(profile, fmt):
    """Запрос к модели через общий транспорт (assist.ask_model)."""
    spec = FORMATS[fmt]
    body = profile.as_prompt()[:MAX_PROFILE_CHARS]
    return ask_model(
        SYSTEM_PROMPT,
        f'ПРОФИЛЬ ПРОЕКТА:\n{body}\n\nЗАДАНИЕ: {spec["about"]}',
        temperature=0.3,        # чуть свободнее, чем подбор: это связный текст
        max_tokens=2000,
        timeout=settings.COMPOSE_TIMEOUT)


def _parse(text):
    """Разбор ответа модели в (блоки, пробелы)."""
    data = json_from_text(text)
    if data is None:
        return [], []
    blocks = []
    for b in (data.get('blocks') or []):
        if not isinstance(b, dict):
            continue
        head = str(b.get('heading') or '').strip()[:200]
        body = str(b.get('text') or '').strip()[:MAX_OUT]
        if head or body:
            blocks.append({'heading': head, 'text': body})
    gaps = [str(g).strip()[:200] for g in (data.get('gaps') or []) if str(g).strip()]
    return blocks, gaps


def compose(profile, fmt):
    """Собрать документ. Возвращает (блоки, пробелы, режим: ok или offline).

    Формат и полноту профиля проверяет вызывающий — до того, как заводить
    задание и тратить поток. Раньше те же проверки дублировались здесь и
    после перехода на фоновое выполнение стали недостижимы.
    """
    raw = _ask_model(profile, fmt)
    if raw is None:
        return [], [], 'offline'
    blocks, gaps = _parse(raw)
    if not blocks:
        log.info('Сборка документа: модель вернула пустой или неразборный ответ')
        return [], [], 'offline'
    return blocks, gaps, 'ok'


def run_job(job_id):
    """Выполнить задание в отдельном потоке."""
    try:
        _run(job_id)
    finally:
        # закрываем при любом исходе: Django открывает соединение на каждый
        # поток, и незакрытые копятся до исчерпания пула. Раньше закрытие
        # стояло только на разобранных путях — необычная ошибка базы утекала
        # мимо него.
        connection.close()


def _run(job_id):
    try:
        job = ComposeJob.objects.select_related('profile').get(pk=job_id)
    except ComposeJob.DoesNotExist:
        return
    try:
        # Проект берём у задания, а не у компании: проектов несколько,
        # и «профиль компании» больше не существует как единственная вещь.
        profile = job.profile
        if profile is None:
            # профиль исчез между постановкой и выполнением — для клиента это
            # то же, что недоступная модель. Пара failed+need была невозможной:
            # клиент рисовал по ней «Сначала заполните» с пустым списком.
            job.status, job.mode = 'failed', 'offline'
        else:
            blocks, gaps, mode = compose(profile, job.fmt)
            job.blocks, job.gaps, job.mode = blocks, gaps, mode
            job.status = 'done' if mode == 'ok' else 'failed'
    except Exception:                       # noqa: BLE001 — поток не должен молча умереть
        log.exception('Сборка документа не удалась (задание %s)', job_id)
        job.status, job.mode = 'failed', 'offline'
    finally:
        job.finished_at = timezone.now()
        # SQLite не любит одновременную запись из нескольких потоков; на бою
        # стоит Postgres, где этого нет, но терять готовый результат из-за
        # занятой базы нельзя — пробуем несколько раз.
        for attempt in range(5):
            try:
                job.save(update_fields=['status', 'mode', 'blocks', 'gaps', 'finished_at'])
                break
            except OperationalError:
                if attempt == 4:
                    log.warning('Не удалось записать результат сборки %s', job_id)
                else:
                    time.sleep(0.3 * (attempt + 1))

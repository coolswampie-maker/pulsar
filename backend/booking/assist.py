# --- темы, требующие разрешительных документов ---
# Осознанно НЕ отказываем грубо: легальная научная работа тоже касается этих
# областей (фармацевтика работает с прекурсорами, генетика — с патогенами,
# материаловедение — со взрывобезопасностью). Такие работы действительно
# оформляются только через оператора с проверкой лицензий, поэтому честный
# ответ — перевести на человека, а не читать нотацию.
#
# Границы слов обязательны: без них «яд» ловится внутри «ядерный магнитный
# резонанс», а «взрыв» — внутри «взрывобезопасности», и мы блокируем
# совершенно нормальные запросы.
LICENSED_PATTERNS = [
    r'взрывчат\w*',
    r'взрывн\w+\s+устройств\w*',
    r'отравляющ\w*\s+вещест\w*',
    r'\bбоев\w+\s+отравляющ\w*',
    r'(химическ\w+|биологическ\w+|бактериологическ\w+|ядерн\w+)\s+оруж\w+',
    r'\bоружи\w*\b',
    r'наркотическ\w*|наркотик\w*|психотропн\w*',
    r'\bпрекурсор\w*',
    r'сильнодействующ\w*\s+вещест\w*',
    r'\bяд\b|\bяда\b|\bяды\b|\bядов\b',           # без границ поймало бы «ядерный»
    r'патоген\w*\s+(iii|iv|3|4)\s*групп\w*',
    r'\bбоеприпас\w*|\bвзрывател\w*',
]
_LICENSED_RE = re.compile('|'.join(LICENSED_PATTERNS), re.IGNORECASE)

LICENSED_REPLY = (
    'Такие работы через автоматический подбор не оформляются: они требуют '
    'лицензий и разрешительных документов. Опишите задачу в заявке — оператор '
    'ПУЛЬСАР свяжется с вами и рассмотрит её отдельно.'
)


def needs_license(query):
    """Затрагивает ли запрос область, требующую разрешений."""
    return bool(_LICENSED_RE.search(query or ''))


MAX_REPLY_LEN = 600      # длинные простыни в интерфейсе не нужны


def _parse_model_json(text):
    """Достаём из ответа модели пару (реплика, позиции).

    Модели любят заворачивать JSON в ```json, поэтому берём первый блок от {
    до последней }. Если разобрать не удалось — возвращаем пустое, вызывающий
    код уйдёт на локальный подбор.
    """
    if not text:
        return '', []
    m = re.search(r'\{.*\}', text, re.S)
    if not m:
        return '', []
    try:
        data = json.loads(m.group(0))
    except (ValueError, TypeError):
        return '', []
    if not isinstance(data, dict):
        return '', []
    reply = str(data.get('reply') or '').strip()[:MAX_REPLY_LEN]
    items = data.get('items')
    return reply, (items if isinstance(items, list) else [])


def model_uri():
    """Адрес модели для API.

    YANDEX_MODEL можно задавать двумя способами, оба рабочие:
      · слаг            — yandexgpt-lite/latest (папка подставится сама);
      · полный адрес    — gpt://<folder>/yandexgpt-lite/latest.
    В документации Яндекса и в карточках моделей встречаются оба варианта,
    поэтому не заставляем помнить, какой именно нужен.
    """
    model = (getattr(settings, 'YANDEX_MODEL', '') or '').strip()
    if model.startswith('gpt://') or model.startswith('ds://'):
        return model
    return f'gpt://{getattr(settings, "YANDEX_FOLDER_ID", "")}/{model}'


def ask_yandex(query, resources):
    """Запрос к YandexGPT. Возвращает список {id, why} либо None при любой
    неудаче — вызывающий код в этом случае откатывается на локальный подбор."""
    key = getattr(settings, 'YANDEX_API_KEY', '')
    folder = getattr(settings, 'YANDEX_FOLDER_ID', '')
    if not key or not folder:
        return None

    import urllib.error
    import urllib.request

    body = {
        'modelUri': model_uri(),
        'completionOptions': {
            'stream': False,
            'temperature': 0.1,      # подбор, а не сочинение: нужна стабильность
            'maxTokens': 800,
        },
        'messages': [
            {'role': 'system', 'text': SYSTEM_PROMPT},
            {'role': 'user',
             'text': f'КАТАЛОГ (идентификатор | тип | название | подразделение | '
                     f'класс | характеристики | описание):\n{_catalog_for_prompt(resources)}\n\n'
                     f'ЗАДАЧА КЛИЕНТА: {query}'},
        ],
    }
    req = urllib.request.Request(
        settings.YANDEX_LLM_URL,
        data=json.dumps(body).encode('utf-8'),
        headers={'Content-Type': 'application/json',
                 'Authorization': f'Api-Key {key}'},
        method='POST')
    try:
        with urllib.request.urlopen(req, timeout=settings.ASSIST_TIMEOUT) as resp:
            payload = json.loads(resp.read().decode('utf-8'))
        text = payload['result']['alternatives'][0]['message']['text']
    except (urllib.error.URLError, OSError, KeyError, IndexError, ValueError) as e:
        log.warning('YandexGPT недоступен, работаем на локальном подборе: %s', e)
        return None
    return _parse_model_json(text)


LOCAL_REPLY_FOUND = 'Вот что подходит под вашу задачу:'
LOCAL_REPLY_WEAK = ('Точного совпадения в каталоге нет. Возможно, подойдёт что-то '
                    'из этого — а если нет, оставьте индивидуальную заявку:')
LOCAL_REPLY_EMPTY = ('По такому описанию в каталоге ничего не нашлось. '
                     'Оставьте индивидуальную заявку — оператор подберёт под задачу.')


def assist(query, resources):
    """Точка входа.

    Возвращает (позиции с обоснованием, режим, реплика клиенту). Режимы:
      · licensed — тема требует разрешений, к модели не обращаемся;
      · ai       — подобрала модель;
      · local    — подобрал встроенный алгоритм;
      · empty    — пустой запрос.
    """
    query = (query or '').strip()[:MAX_QUERY_LEN]
    if not query:
        return [], 'empty', ''

    # Проверка до обращения к модели: она не зависит от промпта, работает и
    # при отключённой модели, и её нельзя обойти уговорами в тексте запроса.
    if needs_license(query):
        log.info('Запрос отнесён к требующим разрешений, к модели не обращаемся')
        return [], 'licensed', LICENSED_REPLY

    by_id = {r.slug: r for r in resources}
    answer = ask_yandex(query, resources)

    if answer is not None:
        reply, raw = answer
        picked, seen = [], set()
        for item in raw:
            if not isinstance(item, dict):
                continue
            rid = str(item.get('id') or '').strip()
            # ключевая проверка: идентификатора нет в каталоге — позиция выдумана
            if rid not in by_id or rid in seen:
                continue
            seen.add(rid)
            picked.append((by_id[rid], str(item.get('why') or '').strip()[:300]))
            if len(picked) >= MAX_RESULTS:
                break
        # Реплика без позиций — нормальный ответ: так модель отвечает на «кто ты»,
        # на посторонние темы и когда в каталоге действительно ничего нет.
        # Но если модель ЧТО-ТО предлагала и всё оказалось выдумкой, её реплику
        # («вот три подходящих прибора») показывать нельзя — она описывает то,
        # что мы только что выбросили. Такой ответ считаем несостоявшимся.
        if picked:
            return picked, 'ai', reply
        if reply and not raw:
            return [], 'ai', reply
        log.info('Модель не дала ни реплики, ни существующих позиций — локальный подбор')

    found, strong = rank_local(query, resources)
    if not found:
        return [], 'local', LOCAL_REPLY_EMPTY
    return ([(r, '') for r in found], 'local',
            LOCAL_REPLY_FOUND if strong else LOCAL_REPLY_WEAK)
